"""Builds astro/stars.js for the Orion Astrolabe from the HYG Database v4.1 (astronexus, CC BY-SA 4.0).

  python -I mkstars_hyg.py <hygdata_v41.csv> <out stars.js>

Reads the CSV (ra in hours, dec in degrees, J2000; mag = visual magnitude; spect = spectral type), keeps the stars of
magnitude 5.5 or brighter (not the Sun), packs them 6 bytes each, brightest first, and finds the 23 Orion figure stars.
The output file is a derivative of the HYG Database and carries the same licence (CC BY-SA 4.0); its header says so.
ASCII only, on purpose."""
import sys, csv, math, base64, struct

SRC, OUT = sys.argv[1], sys.argv[2]
SPEC = 'OBAFGKM'
rows = []
with open(SRC, newline='', encoding='utf-8') as f:
    for r in csv.DictReader(f):
        if r['id'] == '0' or r['proper'] == 'Sol':
            continue
        try:
            rows.append((r['id'], r['proper'] or r['bf'] or ('HIP ' + r['hip'] if r['hip'] else 'HD ' + r['hd'] if r['hd'] else 'id ' + r['id']),
                         float(r['ra']), float(r['dec']), float(r['mag']), (r['spect'] or 'A')[0].upper()))
        except ValueError:
            pass   # a row with no usable position or magnitude
print('catalogue rows read', len(rows))

sel = sorted((r for r in rows if r[4] <= 5.5), key=lambda r: r[4])   # brightest first, so a lighter tier can take a prefix
buf = bytearray()
for _id, name, ra, dec, mag, sp in sel:
    buf += struct.pack('<HhBB', int(round(ra / 24.0 * 65535)) % 65536, int(round(dec * 100)), int(round((mag + 2) * 20)), SPEC.index(sp) if sp in SPEC else 2)
print('stars kept (mag <= 5.5)', len(sel), 'bytes', len(buf))

# the Orion figure: nominal J2000 positions of the 23 stars; each is matched to the catalogue's own row
FIG = [
 ('Betelgeuse', 5.9195, 7.407), ('Meissa', 5.5856, 9.934), ('Bellatrix', 5.4189, 6.350), ('Mintaka', 5.5334, -0.299),
 ('Alnilam', 5.6036, -1.202), ('Alnitak', 5.6793, -1.943), ('Saiph', 5.7959, -9.670), ('Rigel', 5.2423, -8.202),
 ('mu', 6.0397, 9.648), ('nu', 6.1260, 14.768), ('xi', 6.1990, 14.209), ('chi2', 6.0653, 20.138), ('chi1', 5.9064, 20.277),
 ('pi1', 4.9149, 10.151), ('pi2', 4.8436, 8.900), ('pi3', 4.8304, 6.961), ('pi4', 4.8533, 5.605), ('pi5', 4.9043, 2.441), ('pi6', 4.9759, 1.714),
 ('o2', 4.9395, 13.515),
 ('c42', 5.5898, -4.838), ('theta1', 5.5878, -5.390), ('iota', 5.5906, -5.910),
]
def sep(ra1h, d1, ra2h, d2):
    a1, b1, a2, b2 = math.radians(ra1h * 15), math.radians(d1), math.radians(ra2h * 15), math.radians(d2)
    c = math.sin(b1) * math.sin(b2) + math.cos(b1) * math.cos(b2) * math.cos(a1 - a2)
    return math.degrees(math.acos(max(-1.0, min(1.0, c))))
fig = []
for nm, ra, dec in FIG:
    near = sorted(((sep(ra, dec, r[2], r[3]), r) for r in rows), key=lambda t: t[0])[:12]
    close = [t for t in near if t[0] <= 0.02]                      # within 1.2 arcmin: take the brightest (a multiple star's combined light)
    d, best = min(close, key=lambda t: t[1][4]) if close else near[0]
    print('%-10s -> %-18s sep %.4f deg  V %.2f %s%s' % (nm, best[1], d, best[4], best[5], '' if d <= 0.02 else '   <-- not close'))
    if d > 0.3:
        raise SystemExit('no catalogue star near ' + nm)
    fig.append((nm, best[2], best[3], best[4], best[5]))

js = []
js.append('/* Star data for the Orion Astrolabe. Generated by mkstars_hyg.py - do not edit by hand.')
js.append('   SOURCE: the HYG Database v4.1 by astronexus (https://github.com/astronexus/HYG-Database, file hyg/CURRENT/hygdata_v41.csv),')
js.append('   licensed under Creative Commons Attribution-ShareAlike 4.0 International (CC BY-SA 4.0), http://creativecommons.org/licenses/by-sa/4.0/')
js.append('   CHANGES MADE: only the stars of visual magnitude 5.5 or brighter were kept, and only their J2000 right ascension, declination,')
js.append('   magnitude and spectral class, repacked into the compact form below. THIS FILE IS A DERIVATIVE OF THE HYG DATABASE AND IS')
js.append('   LICENSED UNDER THE SAME LICENCE, CC BY-SA 4.0 (see STAR-DATA-LICENCE.txt beside it). No warranty of any kind.')
js.append('   %d stars, brightest first. Each star is 6 bytes:' % len(sel))
js.append('   uint16 RA (0..65535 = 0..24 h), int16 Dec x100, uint8 (V+2)x20, uint8 spectral class index (OBAFGKM). */')
js.append('window.ASTRO_STARS = "%s";' % base64.b64encode(bytes(buf)).decode('ascii'))
js.append('window.ASTRO_ORION = [')
for nm, ra, dec, mag, sp in fig:
    js.append('  ["%s",%.5f,%.4f,%.2f,"%s"],' % (nm, ra, dec, mag, sp))
js.append('];')
text = '\n'.join(js) + '\n'
text.encode('ascii')                                              # fails here, before anything is written
with open(OUT, 'w', newline='\n') as f:
    f.write(text)
print('wrote', OUT, len(text), 'bytes')
